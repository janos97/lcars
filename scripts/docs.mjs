async function manifest() {
  const api = await loadApi();
  return JSON.stringify(
    {
      $comment: GENERATED,
      name: pkg.name,
      version: pkg.version,
      description: pkg.description,
      files: {
        css: "dist/lcars.css",
        cssMin: "dist/lcars.min.css",
        js: "dist/lcars.js",
        fonts: "dist/fonts/",
        cdn: { css: `${CDN}/dist/lcars.min.css`, js: `${CDN}/dist/lcars.js` },
        reference: "docs/reference.md",
        recipes: "docs/recipes.md",
      },
      rules: api.rules,
      mistakes: api.mistakes.map(([dont, fix]) => ({ dont, do: fix })),
      decisions: api.decisions.map(([need, use]) => ({ need, use })),
      components: api.components,
      utilities: api.utilities,
      classes: await documentedClasses(),
      states: api.states.map(([when, appliesTo, effect]) => ({ when, appliesTo, effect })),
      tokens: parseTokens(),
      themes: await parseThemes(),
      attributes: api.attributes.map(([attribute, on, effect]) => ({ attribute, on, effect })),
      js: api.js.map(([member, description]) => ({ member, description })),
      events: api.events.map(([event, detail, when]) => ({ event, detail, when })),
      recipes: parseRecipes().map(({ id, title, summary, page, file }) => ({
        id, title, summary, page, source: `src/recipes/${file}`, live: `examples/recipes/${id}.html`,
      })),
    },
    null,
    2,
  ) + "\n";
}

async function llmsTxt() {
  const api = await loadApi();
  const recipes = parseRecipes();
  return `# LCARS

> Framework-agnostic LCARS (Star Trek computer interface) design system for web apps: plain CSS classes and design tokens in cascade layers, themes for every Star Trek series, and an optional dependency-free ES module. Works with any stack that outputs HTML.

Essentials:
- Load \`${CDN}/dist/lcars.min.css\` (and optionally \`${CDN}/dist/lcars.js\` as a module); put \`class="lcars"\` on <html>.
- Page = \`.lcars-app\` > \`.lcars-frame\` (parts: \`__elbow-top\`, \`__bar-top\`, \`__side\`, \`__main\`, \`__elbow-bottom\`, \`__bar-bottom\`, all direct children).
- Color pieces with \`lcars-c-{primary|secondary|tertiary|accent|muted|alert}\` so themes work; themes via \`data-lcars-theme\` = ${(await parseThemes()).map((t) => t.id).join(", ")}.
- ${api.components.length} components, ${(await documentedClasses()).length} classes, ${parseTokens().length} tokens; every one is listed in the reference and manifest.

## Docs

- [Full context (single file)](${RAW}/llms-full.txt): rules, mistakes, complete reference and all recipes — load this when implementing.
- [API reference](${RAW}/docs/reference.md): rules, components, utilities, tokens, themes, JS.
- [Recipes](${RAW}/docs/recipes.md): copy-paste markup for ${recipes.map((r) => r.id).join(", ")}.
- [Manifest](${RAW}/dist/lcars.manifest.json): the same API as JSON (classes, tokens, themes, attributes).

## Examples

- [Component library](${RAW}/examples/index.html): every component with its source.
- [Operations dashboard](${RAW}/examples/dashboard.html): a complete app.
- [Starter](${RAW}/examples/starter.html): minimal page to copy.

## Optional

- [README](${RAW}/README.md): overview, install, development.
- [Source CSS](https://github.com/${REPO}/tree/${BRANCH}/src/css): tokens.css, themes.css, frame.css, components/.
`;
}

/** Map of repo-relative path → generated contents. */
export async function generateDocs() {
  const reference = await referenceMd();
  const recipes = recipesMd();
  const files = new Map([
    ["docs/reference.md", reference],
    ["docs/recipes.md", recipes],
    ["dist/lcars.manifest.json", await manifest()],
    ["llms.txt", await llmsTxt()],
    [
      "llms-full.txt",
      `# LCARS — full context for AI models\n\n<!-- ${GENERATED} -->\n\nThis file is docs/reference.md followed by docs/recipes.md.\n\n${reference.replace(/^# .*\n/, "")}\n\n---\n\n${recipes}`,
    ],
    ["examples/recipes/index.html", recipeIndex()],
  ]);
  for (const r of parseRecipes()) files.set(`examples/recipes/${r.id}.html`, recipePage(r));
  return files;
}
